// The Node client's half of the generated sets.
//
// Frozen objects of string constants rather than a class hierarchy: a member is
// its own value, so it goes on the wire as itself and a plain string is still
// accepted anywhere one is asked for - the same bargain the Python enums strike,
// reached the way JavaScript reaches it.
package main

import (
	"fmt"
	"strings"

	hw "github.com/MeshBench/meshbench/internal/firmware/board"
	"github.com/MeshBench/meshbench/internal/world/scenario"
)

func jsSets() []byte {
	var b strings.Builder
	b.WriteString(`// Generated by tools/clientgen. DO NOT EDIT.
//
// The closed sets, from internal/world/scenario. Named members rather than free
// strings so an editor can complete them and a member that has gone is
// undefined at the call site - and generated so the list cannot be wrong the
// week somebody adds a board.
//
// Every member is a plain string, so it goes on the wire as itself and a
// literal is still accepted anywhere one of these is asked for. The names match
// the Python client's exactly, so a script moved between the two changes the
// dots and nothing else.

`)
	jsEnum(&b, "Kind", "What a node is.", kinds)

	jsObject(&b, "Board", `A hardware profile this build knows about.

A node's board decides its transmit ceiling, its receive chain's noise figure
and the battery the energy model uses, so naming one that does not exist is
refused rather than defaulted.`, func(b *strings.Builder) {
		for _, bd := range hw.Boards() {
			jsMember(b, screamingIdent(bd.Name), bd.Name,
				fmt.Sprintf("%s, %s, by %s.", bd.MCU, bd.Radio, bd.Vendor))
		}
	})
	jsAll(&b, "Boards", "Board", "Every board")

	jsObject(&b, "Preset", `A named set of LoRa parameters for a territory.

An agreement between operators rather than a configuration, which is why the
list is baked in rather than fetched.`, func(b *strings.Builder) {
		seen := map[string]bool{}
		for _, p := range scenario.RadioPresets {
			id := screamingIdent(p.Label)
			if seen[id] {
				continue
			}
			seen[id] = true
			jsMember(b, id, p.Label, fmt.Sprintf("%.3f MHz, %.1f kHz, SF%d, CR 4/%d.",
				p.FreqMHz, p.BwKHz, p.SF, p.CR))
		}
	})
	jsAll(&b, "Presets", "Preset", "Every preset")
	fmt.Fprintf(&b, "%sexport const DEFAULT_PRESET = %q;\n\n",
		jsDoc("", "What a fresh scenario uses."), scenario.DefaultPreset)

	jsEnum(&b, "Role", `The MeshCore application a node runs, named as upstream names its example
directory.

The string every firmware verb is keyed on. The published catalogue spells some
of the same things differently - "repeater", "room-server" - and those belong to
the release assets; typing one at a verb pins nothing, and the run then refuses
to start with no clue as to why.`, roles)
	jsAll(&b, "Roles", "Role", "Every role")
	jsEnum(&b, "Class", "What happened to an event.", classes)
	jsAll(&b, "Classes", "Class", "Every class")
	jsEnum(&b, "Tab", "A pane of a node's own window.", tabs)
	jsAll(&b, "Tabs", "Tab", "Every tab")
	jsEnum(&b, "Strategy", "How an imported deployment meets what is already loaded.",
		strategies)
	jsEnum(&b, "Transport", "How a served companion is reached.", transports)
	return []byte(b.String())
}

// jsEnum writes one frozen object from a list of sets that carry their own
// member names.
func jsEnum(b *strings.Builder, name, doc string, items []set) {
	jsObject(b, name, doc, func(b *strings.Builder) {
		for _, it := range items {
			jsMember(b, it.Py, it.Value, it.Doc)
		}
	})
}

// jsObject writes the frozen object itself, leaving its members to write.
func jsObject(b *strings.Builder, name, doc string, members func(*strings.Builder)) {
	fmt.Fprintf(b, "%sexport const %s = Object.freeze({\n", jsDoc("", doc), name)
	members(b)
	b.WriteString("});\n\n")
}

func jsMember(b *strings.Builder, name, value, doc string) {
	fmt.Fprintf(b, "%s  %s: %q,\n", jsDoc("  ", doc), name, value)
}

// jsAll writes the array of every member, for a caller offering a choice.
//
// Read off the object rather than listed again, because a second list is a
// second thing to be wrong and this one cannot disagree with the first.
func jsAll(b *strings.Builder, name, of, doc string) {
	fmt.Fprintf(b, "%sexport const %s = Object.freeze(Object.values(%s));\n\n",
		jsDoc("", doc+", for a caller offering a choice."), name, of)
}

// jsDoc wraps prose as a JSDoc comment, for the same reason goComment wraps a
// Go one: a generated line past the margin is a finding nobody can fix without
// editing the generator. A paragraph break in the source survives as one here.
func jsDoc(indent, text string) string {
	var lines []string
	for _, para := range strings.Split(text, "\n\n") {
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, wrap(para, 74-len(indent))...)
	}
	if len(lines) == 1 {
		return fmt.Sprintf("%s/** %s */\n", indent, lines[0])
	}
	var out strings.Builder
	fmt.Fprintf(&out, "%s/**\n", indent)
	for _, l := range lines {
		if l == "" {
			fmt.Fprintf(&out, "%s *\n", indent)
			continue
		}
		fmt.Fprintf(&out, "%s * %s\n", indent, l)
	}
	fmt.Fprintf(&out, "%s */\n", indent)
	return out.String()
}
